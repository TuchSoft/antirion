"""Writes the cell files of the AWS run from the harness's matrix (bench/matrix/cells.yaml).

    uv run --with pyyaml python gen-cells.py <cells.yaml> <out dir>
    uv run --with pyyaml python gen-cells.py --table <cells.yaml>     the comparison table only, on stdout

headline.yaml  the headline cell H1 (simple chat at 5,000 RPS, P-min, mock L0), every target
               interleaved, with the matrix's own windows for it (10 s warm-up, 30 s measurement,
               5 repetitions); docs/benchmarks.md explains the choice
compare.yaml   the comparison cells, all at P-min, 5 s warm-up, 15 s measurement, 3 repetitions
               (saturation ladders: 1 repetition, 7 s steps, from 500 RPS), no gates
c20-<m>.yaml   the published-benchmark cells C20.xlarge and C20.medium, one file each, with their gates
               (no topology requirement: the t3 run names its machines xlarge and medium)
gates.yaml     the release cells that run on one 4 vCPU gateway, 5 s / 20 s / 3 repetitions
               (saturation ladders: 1 repetition, 7 s steps)
gates5.yaml    gates.yaml at 5 repetitions (saturation ladders: 1 repetition), C12 first, for the
               reference topology
c7.yaml        the cluster cell C7, 5 s / 20 s / 3 repetitions
c15.yaml       the scaling cell C15 for ref-16 (saturation ladder, 1 repetition, 7 s steps from
               10,000 RPS)
cmp/<id>.yaml  each comparison cell (the headline's and compare.yaml's) alone, for run.sh --shards: a
               shard's cell file is its cells' files put together
comparison.tsv the comparison cells in run order: id, expected seconds for every target, set
               (headline or compare); run.sh balances the shards with it

Expected seconds of a cell, for all targets (bench/targets/*/target.yaml, and Antirion): per target
and repetition, a gateway run and a direct run (none when the scenario has no direct run) of
warm-up + measurement each, plus OVERHEAD_S to start, settle and stop the target (the t3 run's open
cells took 10.2 to 11.9 min for 3 targets x 3 repetitions of 5 s + 15 s: 28 to 38 s each). A
saturation ladder is assumed to climb to SAT_GUESS_RPS (or its max) and then take every fine step;
idle, startup and apply cells take IDLE_S per target and repetition.
"""

import copy
import glob
import math
import os
import sys

import yaml

TABLE = len(sys.argv) == 3 and sys.argv[1] == "--table"
if len(sys.argv) != 3:
    sys.exit("usage: gen-cells.py <cells.yaml> <out dir> | --table <cells.yaml>")
matrix_file, out = (sys.argv[2], None) if TABLE else (sys.argv[1], sys.argv[2])
with open(matrix_file) as f:
    cells = {c["cell"]: c for c in yaml.safe_load(f)}
bench_dir = os.path.dirname(os.path.dirname(os.path.abspath(matrix_file)))
with open(os.path.join(bench_dir, "matrix", "scenarios.yaml")) as f:
    scenarios = yaml.safe_load(f)
TARGETS = len(glob.glob(os.path.join(bench_dir, "targets", "*", "target.yaml"))) + 1

OVERHEAD_S = 35
SAT_GUESS_RPS = 15000
IDLE_S = 30


def expected_s(c):
    kind, reps = c["kind"], c.get("repetitions", 5)
    run = c.get("warmup_s", 30) + c.get("measure_s", 120)
    direct = c["kind"] != "hold" and scenarios.get(c.get("scenario"), {}).get("direct", True)
    pair = run * (2 if direct else 1)
    if kind in ("open", "closed", "hold"):
        per = pair + OVERHEAD_S
    elif kind == "saturation":
        lad = c["level"]["ladder"]
        top = min(lad["max"], SAT_GUESS_RPS)
        steps = max(0, math.ceil((top - lad["start"]) / lad["step"])) + 1
        steps += math.ceil(lad["step"] / lad.get("fine_step", lad["step"]))
        per = steps * (pair + 5) + OVERHEAD_S
    else:
        per = IDLE_S
    return int(reps * TARGETS * per)

HEADLINE = "H1"
WINDOWS = {"warmup_s": 5, "measure_s": 20, "repetitions": 3}
LADDER_WINDOWS = {"warmup_s": 5, "measure_s": 7, "repetitions": 1}


def windowed(c, windows):
    c = copy.deepcopy(c)
    if c["kind"] in ("open", "closed", "hold", "saturation"):
        c.update(windows)
    elif c["kind"] in ("idle", "startup", "apply"):
        c["repetitions"] = windows["repetitions"]
    return c


def write(name, defs):
    if TABLE:
        return
    os.makedirs(os.path.dirname(f"{out}/{name}"), exist_ok=True)
    with open(f"{out}/{name}", "w") as f:
        f.write(f"# Generated by bench/aws/gen-cells.py from {matrix_file}\n")
        yaml.safe_dump(defs, f, sort_keys=False, default_flow_style=None, width=200)


# The headline: the matrix's cell as it stands, its windows included.
headline = copy.deepcopy(cells[HEADLINE])
for k in ("warmup_s", "measure_s", "repetitions"):
    if k not in headline:
        sys.exit(f"{HEADLINE} must set its own {k} in {matrix_file}")
headline.pop("needs_topology", None)
headline.pop("suites", None)
headline["gates"] = []
headline["compare"] = True
headline["informational"] = True
write("headline.yaml", [headline])

# The comparison: every target at P-min, the cells the previous comparison ran.
COMPARE = ["C1", "C2", "C4", "C5", "C8", "C11", "C13", "C16", "C17", "C21.401", "C21.404", "C32.c64"]
compare = []
for cid in COMPARE:
    c = copy.deepcopy(cells[cid])
    c["cell"] = f"cmp-{cid}"
    c["profile"] = "P-min"
    c["gates"] = []
    c["informational"] = True
    c["compare"] = True
    c.pop("needs_topology", None)
    if c["kind"] == "saturation":
        c["level"] = {"ladder": {"start": 500, "step": 2500, "fine_step": 500, "max": 60000}}
        c.update(LADDER_WINDOWS)
    else:
        c = windowed(c, {"warmup_s": 5, "measure_s": 15, "repetitions": 3})
    compare.append(c)
write("compare.yaml", compare)

# The comparison cell by cell, with what each is expected to take.
table = [(c, "headline") for c in [headline]] + [(c, "compare") for c in compare]
for c, _ in table:
    write(f"cmp/{c['cell']}.yaml", [c])
lines = "".join(f"{c['cell']}\t{expected_s(c)}\t{kind}\n" for c, kind in table)
if TABLE:
    sys.stdout.write(lines)
    sys.exit(0)
with open(f"{out}/comparison.tsv", "w") as f:
    f.write(lines)

c20 = []
for machine in ["xlarge", "medium"]:
    c = copy.deepcopy(cells[f"C20.{machine}"])
    c.pop("needs_topology", None)
    c.update({"warmup_s": 5, "measure_s": 30, "repetitions": 3})
    c20.append(c)
    write(f"c20-{machine}.yaml", [c])

GATES = ["C1", "C2", "C3", "C4", "C5", "C6", "C8", "C9", "C11", "C12", "C13", "C14", "C16", "C17",
         "C19.1MiB", "C19.4MiB", "C19.16MiB", "C21.401", "C21.403", "C21.404", "C21.429", "C22", "C23",
         "C29.1000", "C29.scale", "C31.hanging", "C31.base"]
gates = []
for cid in GATES:
    c = cells[cid]
    if c["kind"] == "saturation":
        c = copy.deepcopy(c)
        big = c["level"]["ladder"]["max"] > 200000
        c["level"] = {"ladder": {"start": 2000, "step": 4000 if big else 2500,
                                 "fine_step": 1000 if big else 500, "max": 120000 if big else 60000}}
        c.update(LADDER_WINDOWS)
    else:
        c = windowed(c, WINDOWS)
    gates.append(c)
write("gates.yaml", gates)
# Reference lane A runs these until the planned wall time: C12 first, since ref-16's C15 gate reads it.
gates5 = [windowed(c, {**WINDOWS, "repetitions": 5}) if c["kind"] != "saturation" else c for c in gates]
gates5.sort(key=lambda c: c["cell"] != "C12")
write("gates5.yaml", gates5)

write("c7.yaml", [windowed(cells["C7"], WINDOWS)])

c15 = copy.deepcopy(cells["C15"])
c15["level"] = {"ladder": {"start": 10000, "step": 10000, "fine_step": 2500, "max": 400000}}
c15.update(LADDER_WINDOWS)
write("c15.yaml", [c15])
print(f"cells: headline 1, compare {len(compare)}, c20 {len(c20)}, gates {len(gates)} (and gates5), c7 1, c15 1")
