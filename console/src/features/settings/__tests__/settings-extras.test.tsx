import { render, screen, waitFor, within } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { http, HttpResponse } from 'msw';
import { beforeEach, describe, expect, it } from 'vitest';

import { emptySlot } from '@/lib/slot';
import { server } from '@/mocks/node';
import { pickOption, signInAs } from '@/test/utils';

import { KeyChecksCard, pepperWords } from '../components/key-checks-card';
import { useOrgSettings } from '../store';

const meta = { etag: '"5"', generation: 5, created_at: null, updated_at: null, managed_by: 'api' };

/** A settings key that answers `spec` and records each PATCH body's spec. */
function settingsKey(key: string, spec: Record<string, unknown>) {
  const patches: Record<string, unknown>[] = [];
  let current = spec;
  server.use(
    http.get(`*/admin/v1/settings/${key}`, () => HttpResponse.json({ spec: current, metadata: meta })),
    http.patch(`*/admin/v1/settings/${key}`, async ({ request }) => {
      const body = (await request.json()) as { spec: Record<string, unknown> };
      patches.push(body.spec);
      current = { ...current, ...body.spec };
      return HttpResponse.json({ spec: current, metadata: { ...meta, etag: '"6"' } });
    }),
  );
  return patches;
}

const card = (title: string) =>
  screen.getByText(title, { selector: 'h3' }).closest('section') ?? document.body;

describe('How keys are checked', () => {
  beforeEach(() => {
    useOrgSettings.setState({
      auth: emptySlot(),
      observability: emptySlot(),
      limits: emptySlot(),
      security: emptySlot(),
    });
    server.use(
      http.get('*/admin/v1/settings/observability', () => HttpResponse.json({ spec: {}, metadata: meta })),
      http.get('*/admin/v1/settings/limits', () => HttpResponse.json({ spec: {}, metadata: meta })),
      http.get('*/admin/v1/settings/security', () => HttpResponse.json({ spec: {}, metadata: meta })),
    );
  });

  it('shows the defaults and the rules kept in the configuration, and writes one change', async () => {
    signInAs(['security:read', 'security:write']);
    const patches = settingsKey('auth', {
      access_rules: [{ models: ['gpt-*'], require: { key_tags: ['prod'] } }],
      model_groups: { cheap: ['gpt-4.1-mini'] },
      key_pepper: '[REDACTED]',
    });
    render(<KeyChecksCard />);
    const c = await waitFor(() => card('How keys are checked'));
    expect(within(c).getByRole('combobox', { name: 'A revoked key stops working within' })).toHaveTextContent(
      '2 seconds',
    );
    await userEvent.click(within(c).getByText('Rules set in the configuration'));
    expect(within(c).getByText('1 rule')).toBeInTheDocument();
    expect(within(c).getByText('cheap')).toBeInTheDocument();
    expect(within(c).getByText('Set in the configuration')).toBeInTheDocument();
    await pickOption(within(c).getByRole('combobox', { name: /While the store is down/ }), '1 hour');
    await userEvent.click(within(c).getByRole('button', { name: 'Save changes' }));
    await waitFor(() => expect(patches).toEqual([{ store_outage_grace: '1h' }]));
  });

  it('says how the key pepper is kept', () => {
    expect(pepperWords(undefined)).toBe('Generated by the gateway and kept in its store');
    expect(pepperWords('${env:PEPPER}')).toBe('Set, from the environment variable PEPPER');
  });
});
